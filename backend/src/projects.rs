//! Literature-review workspace helpers.
//!
//! A project groups papers for one reading goal. CRUD lives in `Store`; this
//! module renders the exportable readout entirely from the deterministic
//! extraction plus the user's own notes and follow-ups, so a readout can be
//! regenerated at any time without drift.

use crate::models::{Paper, Project};
use std::collections::HashMap;

fn clean_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn clip(s: &str, max: usize) -> String {
    let s = clean_line(s);
    if s.chars().count() <= max { return s; }
    let cut: String = s.chars().take(max.saturating_sub(1)).collect();
    format!("{cut}…")
}

fn paper_label(p: &Paper) -> String {
    let meta = [
        p.year.map(|y| y.to_string()),
        p.venue.clone(),
    ].into_iter().flatten().collect::<Vec<_>>().join(" · ");
    if meta.is_empty() { p.title.clone() } else { format!("{} ({meta})", p.title) }
}

/// Render a self-contained markdown readout for one project.
pub fn readout(project: &Project, papers: &[Paper]) -> String {
    let mut out = String::new();
    out.push_str(&format!("# {}\n\n", project.name));
    if !project.description.trim().is_empty() {
        out.push_str(&format!("> {}\n\n", clean_line(&project.description)));
    }
    if !project.tags.is_empty() {
        out.push_str(&format!("**Tags:** {}\n\n", project.tags.join(", ")));
    }
    out.push_str(&format!(
        "_Generated by Paper Explainer from {} paper(s). Follow-ups and notes below are yours._\n\n",
        project.paper_ids.len(),
    ));

    // -- Overview table -----------------------------------------------------
    if !papers.is_empty() {
        out.push_str("## Papers at a glance\n\n");
        out.push_str("| # | Paper | Hypotheses | Findings | Category |\n");
        out.push_str("|---|-------|-----------|----------|----------|\n");
        for (i, p) in papers.iter().enumerate() {
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} |\n",
                i + 1,
                clip(&paper_label(p), 90).replace('|', "\\|"),
                p.hypotheses.len(), p.findings.len(),
                if p.primary_category.is_empty() { "—".into() } else { p.primary_category.clone() },
            ));
        }
        out.push('\n');
    }

    // -- Per-paper detail ---------------------------------------------------
    if !papers.is_empty() {
        out.push_str("## Paper notes\n\n");
        for (i, p) in papers.iter().enumerate() {
            out.push_str(&format!("### {}. {}\n\n", i + 1, p.title));
            let authors = if p.authors.is_empty() { "Unknown authors".into() } else { p.authors.join(", ") };
            out.push_str(&format!("**Authors:** {authors}  \n"));
            if !p.url.is_empty() { out.push_str(&format!("**Source:** <{}>  \n", p.url)); }
            if let Some(id) = &p.arxiv_id { out.push_str(&format!("**arXiv:** {id}  \n")); }
            if let Some(id) = &p.doi { out.push_str(&format!("**DOI:** {id}  \n")); }
            out.push('\n');

            if !p.summary.trim().is_empty() {
                out.push_str(&format!("**In short.** {}\n\n", clean_line(&p.summary)));
            }

            if !p.hypotheses.is_empty() {
                out.push_str("**Hypotheses**\n\n");
                for h in &p.hypotheses {
                    out.push_str(&format!("- [{}] {} — _{}_\n",
                        format!("{:?}", h.status).replace('_', " "),
                        clean_line(&h.statement),
                        if h.simplified.is_empty() { "no plain-language version".into() } else { clip(&h.simplified, 200) },
                    ));
                }
                out.push('\n');
            }

            if !p.findings.is_empty() {
                out.push_str("**Findings**\n\n");
                out.push_str("| Claim | Evidence | Caveat |\n|-------|----------|--------|\n");
                for f in &p.findings {
                    out.push_str(&format!("| {} | {} | {} |\n",
                        clip(&f.claim, 140).replace('|', "\\|"),
                        clip(&f.evidence, 100).replace('|', "\\|"),
                        f.caveat.as_deref().map(|c| clip(c, 100)).unwrap_or_else(|| "—".into()).replace('|', "\\|"),
                    ));
                }
                out.push('\n');
            }

            if !p.tags.is_empty() {
                out.push_str(&format!("**Tags:** {}\n\n", p.tags.join(", ")));
            }
        }
    } else {
        out.push_str("_No papers have been added to this project yet._\n\n");
    }

    // -- Shared themes ------------------------------------------------------
    let mut concept_papers: HashMap<&str, Vec<&str>> = HashMap::new();
    for p in papers {
        for c in &p.concepts {
            let entry = concept_papers.entry(&c.name).or_default();
            if !entry.contains(&p.id.as_str()) { entry.push(&p.id); }
        }
    }
    let mut shared: Vec<(&str, usize)> = concept_papers.into_iter()
        .filter(|(_, ids)| ids.len() > 1)
        .map(|(name, ids)| (name, ids.len()))
        .collect();
    shared.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
    if !shared.is_empty() {
        out.push_str("## Shared themes\n\n");
        for (name, count) in shared.into_iter().take(20) {
            out.push_str(&format!("- **{name}** — appears in {count} papers\n"));
        }
        out.push('\n');
    }

    // -- Within-project citations ------------------------------------------
    let id_set: Vec<&str> = papers.iter().map(|p| p.id.as_str()).collect();
    let mut links = Vec::new();
    for p in papers {
        for r in &p.references {
            if let Some(target) = &r.resolved_paper_id {
                if id_set.contains(&target.as_str()) {
                    links.push((p.title.clone(), target.clone()));
                }
            }
        }
    }
    links.sort();
    links.dedup();
    if !links.is_empty() {
        out.push_str("## Citations within this project\n\n");
        for (from, to) in links {
            let label = papers.iter().find(|p| p.id == to)
                .map(|p| p.title.clone()).unwrap_or_else(|| to.clone());
            out.push_str(&format!("- “{}” cites “{}”\n", clip(&from, 80), clip(&label, 80)));
        }
        out.push('\n');
    }

    // -- User notes and follow-ups -----------------------------------------
    out.push_str("## My notes\n\n");
    if project.notes.trim().is_empty() {
        out.push_str("_No project notes yet._\n\n");
    } else {
        out.push_str(&project.notes.trim());
        out.push_str("\n\n");
    }

    out.push_str("## Follow-ups\n\n");
    let title_by_id: HashMap<&str, &str> = papers.iter()
        .map(|p| (p.id.as_str(), p.title.as_str())).collect();
    let open: Vec<_> = project.follow_ups.iter().filter(|f| !f.done).collect();
    let done: Vec<_> = project.follow_ups.iter().filter(|f| f.done).collect();
    if open.is_empty() && done.is_empty() {
        out.push_str("_No follow-ups yet._\n\n");
    } else {
        if !open.is_empty() {
            out.push_str("### To do\n\n");
            for f in open { push_task(&mut out, f, &title_by_id, false); }
            out.push('\n');
        }
        if !done.is_empty() {
            out.push_str("### Done\n\n");
            for f in done { push_task(&mut out, f, &title_by_id, true); }
            out.push('\n');
        }
    }

    out.push_str("---\n\n");
    out.push_str("_Claims, numbers and caveats above come from each paper's deterministic extraction. Always check the cited section before relying on a result._\n");
    out
}

fn push_task(out: &mut String, f: &crate::models::ProjectFollowUp, titles: &HashMap<&str, &str>, done: bool) {
    let paper = f.paper_id.as_deref()
        .and_then(|id| titles.get(id).map(|t| format!(" — _{}_", clip(t, 70))))
        .unwrap_or_default();
    out.push_str(&format!("- [{}] **{}**{paper}\n", if done { "x" } else { " " }, clean_line(&f.title)));
    if !f.notes.trim().is_empty() {
        out.push_str(&format!("  - {}\n", clean_line(&f.notes)));
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::{Finding, Hypothesis, ProjectFollowUp};

    #[test]
    fn readout_includes_papers_findings_notes_and_tasks() {
        let mut p = Paper::default();
        p.id = "p1".into();
        p.title = "A Great Paper".into();
        p.summary = "It studies things.".into();
        p.hypotheses.push(Hypothesis {
            statement: "Things improve.".into(), simplified: "Better results.".into(), ..Default::default()
        });
        p.findings.push(Finding {
            claim: "12% gain".into(), evidence: "Table 2".into(),
            caveat: Some("Only on one dataset".into()), ..Default::default()
        });
        p.concepts.push(crate::models::Concept {
            id: "c".into(), name: "Obfuscation".into(), definition: "Hiding".into(),
            category: "primitive".into(), aliases: Vec::new(),
        });

        let mut project = Project::default();
        project.name = "My review".into();
        project.description = "A reading project".into();
        project.paper_ids = vec!["p1".into()];
        project.notes = "Follow up on the dataset".into();
        project.follow_ups.push(ProjectFollowUp {
            title: "Email the authors".into(), done: false, ..Default::default()
        });

        let md = readout(&project, &[p]);
        assert!(md.starts_with("# My review"));
        assert!(md.contains("A Great Paper"));
        assert!(md.contains("12% gain"));
        assert!(md.contains("Follow up on the dataset"));
        assert!(md.contains("- [ ] **Email the authors**"));
        assert!(md.contains("Always check the cited section"));
    }
}
